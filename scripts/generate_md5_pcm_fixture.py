"""Regenerate MD5 PCM regressions using Python hashlib, without MoonFLAC.

python scripts/generate_md5_pcm_fixture.py
Then format only the generated file: moonfmt -w md5_pcm_wbtest.mbt
"""
import hashlib
from pathlib import Path

SIZES = [1, 7, 16, 31, 1, 1, 7, 1, 64, 65]


def sample(bits, channel, index, flavor):
    half = 1 << (bits - 1)
    values = [-half, half - 1, -1, 0, 1, -(half // 2), (half - 1) // 2,
              (index * 104729 + channel * 32771 + bits * 521) % (1 << bits) - half]
    value = values[(index + channel * 3) % 8]
    return value if flavor == 0 else -1 - value


def expected(bits, channels):
    states = [hashlib.md5(), hashlib.md5()]
    transcript = bytearray()
    offset = 0
    for count in SIZES:
        for flavor, state in enumerate(states):
            pcm = b''.join(sample(bits, channel, i, flavor).to_bytes((bits + 7) // 8, 'little', signed=True)
                           for i in range(offset, offset + count) for channel in range(channels))
            state.update(pcm)
            transcript += state.digest()
        offset += count
    return hashlib.md5(transcript).digest()


BODY = r'''
///|
fn md5_pcm_fixture_frame(bits : Int, channels : Int, offset : Int, count : Int, flavor : Int) -> Frame {
  let half = 1L << (bits - 1)
  let planar = Array::makei(channels, channel => Array::makei(count, at => {
    let index = offset + at
    let values = [
      -half, half - 1L, -1L, 0L, 1L, -(half / 2L), (half - 1L) / 2L,
      (index.to_int64() * 104729L + channel.to_int64() * 32771L + bits.to_int64() * 521L) % (1L << bits) - half,
    ]
    let value = values[(index + channel * 3) % 8]
    (if flavor == 0 { value } else { -1L - value }).to_int()
  }))
  {
    sample_number: offset.to_int64(), number: offset.to_int64(),
    variable_block: true, sample_rate: 48000, bits_per_sample: bits,
    channels: planar, block_size: count, byte_offset: 0L, byte_length: 0,
  }
}

///|
test "MD5 PCM hashlib oracle all depths channels padding and state ownership" {
  // The transcript contains both independent state digests after each frame,
  // in order A then B. Its expected hash comes only from Python hashlib.
  // Sizes cross 55/56/57/64/65-byte padding boundaries for 8-bit mono and
  // exercise interleaving and sign extension for every other PCM format.
  let sizes = [1, 7, 16, 31, 1, 1, 7, 1, 64, 65]
  for bits = 4; bits <= 32; bits = bits + 1 {
    for channels = 1; channels <= 8; channels = channels + 1 {
      let a = Md5::new()
      let b = Md5::new()
      let transcript = Md5::new()
      let mut offset = 0
      let empty_a = a.digest()
      let empty_b = b.digest()
      assert_eq(empty_a, b"\xd4\x1d\x8c\xd9\x8f\x00\xb2\x04\xe9\x80\x09\x98\xec\xf8\x42\x7e")
      for count in sizes {
        md5_update_frame(a, md5_pcm_fixture_frame(bits, channels, offset, count, 0))
        let retained_a = a.digest()
        assert_eq(a.digest(), retained_a)
        transcript.update(retained_a)
        let before_b = b.digest()
        md5_update_frame(b, md5_pcm_fixture_frame(bits, channels, offset, count, 1))
        let retained_b = b.digest()
        transcript.update(retained_b)
        // Finalizing/updating B and transcript must not mutate A's state or
        // already returned digest storage. Finalization itself is repeatable.
        assert_eq(a.digest(), retained_a)
        assert_eq(b.digest(), retained_b)
        if offset == 0 { assert_eq(before_b, empty_b) }
        offset += count
        assert_eq(a.length, (offset * channels * ((bits + 7) / 8)).to_int64())
        assert_eq(b.length, a.length)
        assert_eq(a.used, a.length.to_int() % 64)
        assert_eq(b.used, a.used)
      }
      assert_eq(transcript.digest(), md5_pcm_expected[(bits - 4) * 8 + channels - 1])
      assert_eq(empty_a, empty_b)
      assert_eq(empty_a, b"\xd4\x1d\x8c\xd9\x8f\x00\xb2\x04\xe9\x80\x09\x98\xec\xf8\x42\x7e")
    }
  }
}
'''


def main():
    text = '// Generated by scripts/generate_md5_pcm_fixture.py; Python hashlib oracle.\n'
    text += '///|\nlet md5_pcm_expected : Array[Bytes] = [\n'
    for bits in range(4, 33):
        for channels in range(1, 9):
            value = ''.join(f'\\x{byte:02x}' for byte in expected(bits, channels))
            text += f'  b"{value}", // {bits}-bit, {channels} channels\n'
    text += ']\n' + BODY
    path = Path(__file__).resolve().parents[1] / 'md5_pcm_wbtest.mbt'
    path.write_text(text, encoding='utf-8')
    print('Generated 232 independent hashlib transcript expectations; no MoonFLAC reference used.')


if __name__ == '__main__':
    main()
