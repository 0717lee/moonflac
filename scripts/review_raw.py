#!/usr/bin/env python3
"""Independent regression oracle for valid FLAC frames nested inside PCM."""
from __future__ import annotations
import ctypes
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
from validate import LibFLAC, library

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / "validation/cache/review-raw"
BUILD = ROOT / "_build/review-raw"
PACKAGE = ROOT / "validation/review_raw"
REPORT = ROOT / "validation/evidence/review-raw.json"


def crc(data: bytes, width: int, polynomial: int) -> int:
    value = 0
    for octet in data:
        value ^= octet << (width - 8)
        for _ in range(8):
            value = ((value << 1) ^ (polynomial if value & (1 << (width-1)) else 0)) & ((1 << width)-1)
    return value


def frame(subframe: bytes) -> bytes:
    # RFC 9639: fixed block, block-size extension16, rate48k, mono16bit, frame0.
    header = bytes.fromhex("ff f8 6a 08 00 0f")
    body = header + bytes([crc(header, 8, 0x07)]) + subframe
    return body + crc(body, 16, 0x8005).to_bytes(2, "big")


def wrap(raw: bytes, samples: list[int]) -> bytes:
    # Minimal STREAMINFO: block16, exact frame length, 48kHz mono16, 16samples.
    pcm = struct.pack("<16h", *samples)
    info = struct.pack(">HH", 16, 16) + len(raw).to_bytes(3,"big") * 2
    info += ((48000 << 44) | (15 << 36) | 16).to_bytes(8,"big")
    info += hashlib.md5(pcm).digest()
    assert len(info) == 34
    return b"fLaC\x80\x00\x00\x22" + info + raw


def literal(data: bytes) -> str:
    return 'b"' + ''.join(f'\\x{x:02x}' for x in data) + '"'


def main() -> None:
    CACHE.mkdir(parents=True, exist_ok=True)
    PACKAGE.mkdir(parents=True, exist_ok=True)
    ref = LibFLAC(library(None))
    version = ctypes.c_char_p.in_dll(ref.dll, "FLAC__VERSION_STRING").value.decode()
    cases = []
    for offset, value in [(0, 123), (2, -2345), (8, 16384), (20, -32768)]:
        inner = frame(b"\x00" + struct.pack(">h", value))
        assert len(inner) == 12
        payload = bytearray(32)
        payload[offset:offset+12] = inner
        raw = frame(b"\x02" + payload)  # verbatim subframe, all16 samples.
        assert len(raw) == 42
        structural_samples = list(struct.unpack(">16h", payload))
        source = CACHE / f"nested-{offset}.flac"
        source.write_bytes(wrap(raw, structural_samples))
        props, expected = ref.decode(source)
        assert props == (1, 16, 48000) and expected == structural_samples
        # Verify that the tempting embedded sequence is itself a valid frame.
        inner_source = CACHE / f"inner-{offset}.flac"
        inner_source.write_bytes(wrap(inner, [value] * 16))
        inner_props, inner_pcm = ref.decode(inner_source)
        assert inner_props == props and inner_pcm == [value] * 16
        cases.append(dict(payload_offset=offset, inner_value=value,
                          raw_frame_hex=raw.hex(), expected_pcm=expected,
                          source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                          pcm_sha256=hashlib.sha256(struct.pack("<16h",*expected)).hexdigest(),
                          independent_decode="libFLAC accepted outer and inner; exact PCM and MD5 checked"))
    code = '''// Generated by scripts/review_raw.py; expected PCM comes from libFLAC.
///|
fn check_chunks(data : Bytes, expected : Array[Int], cuts : Array[Int]) -> Unit raise {
  let decoder = @flac.RawDecoder::new()
  let mut frames = 0
  let mut position = 0
  for end in cuts {
    assert_eq(decoder.push(data[position:end].to_owned()), end - position)
    position = end
    while true {
      match decoder.next() {
        RawNeedInput => break
        RawFrame(frame) => {
          // A nested complete frame must never be emitted from a partial outer.
          assert_eq(position, data.length())
          assert_eq(frames, 0)
          assert_eq(frame.block_size, 16)
          assert_eq(frame.sample_rate, 48000)
          assert_eq(frame.bits_per_sample, 16)
          assert_eq(frame.channels.length(), 1)
          assert_eq(frame.channels[0], expected)
          frames += 1
        }
        Skipped(_, _) => fail("valid outer frame bytes were discarded")
        RawDone => fail("done before finish")
      }
    }
  }
  decoder.finish()
  while true {
    match decoder.next() {
      RawDone => break
      RawFrame(frame) => {
        assert_eq(frames, 0)
        assert_eq(frame.channels[0], expected)
        frames += 1
      }
      _ => fail("unexpected finish event")
    }
  }
  assert_eq(frames, 1)
}
'''
    for case in cases:
        data = bytes.fromhex(case["raw_frame_hex"])
        code += f'''
///|
test "libFLAC nested PCM offset {case['payload_offset']}" {{
  let data = {literal(data)}
  let expected : Array[Int] = {case['expected_pcm']}
  for split in 0..=data.length() {{
    check_chunks(data, expected, [split, data.length()])
  }}
  // Every three-part partition, including empty segments and two short prefixes.
  for first in 0..=data.length() {{
    for second in first..=data.length() {{
      check_chunks(data, expected, [first, second, data.length()])
    }}
  }}
  check_chunks(data, expected, Array::makei(data.length(), i => i + 1))
}}
'''
    (PACKAGE / "golden_test.mbt").write_text(code, encoding="utf-8")
    (PACKAGE / "moon.pkg").write_text('import { "0717lee/moonflac" @flac }\n', encoding="utf-8")
    subprocess.run(["moon", "fmt", "validation/review_raw", "--target-dir", str(BUILD / "fmt")], cwd=ROOT, check=True)
    commands = [["moon", "test", "--target", target, "--target-dir", str(BUILD / f"build-{target}"), "validation/review_raw"]
                for target in ("native", "js", "wasm-gc")]
    tests = []
    for command in commands:
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
        log = CACHE / f"{command[3]}.log"
        log.write_text(result.stdout + result.stderr, encoding="utf-8")
        tests.append(dict(command=command, returncode=result.returncode,
                          output=result.stdout, log=str(log.relative_to(ROOT))))
        print(command[3], result.returncode, result.stdout[-500:], flush=True)
    report = dict(oracle=f"libFLAC {version}", generation_command="python scripts/review_raw.py",
                  specification="RFC9639 sections9.1,9.2.3,9.2.4,9.3 and8.2",
                  cases=cases, tests=tests,
                  coverage="4layouts × (43 two-part + 946 three-part + 1 bytewise)=3960 chunkings/backend",
                  status="pass" if all(x["returncode"] == 0 for x in tests) else "fail")
    REPORT.write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    if report["status"] != "pass": raise SystemExit(1)


def corpus() -> None:
    """Bounded raw multicast regression; never overwrite baseline evidence."""
    CACHE.mkdir(parents=True, exist_ok=True)
    build = ROOT / "_build/review-raw-runner"
    command = ["moon", "build", "--target", "native", "--target-dir", str(build), "validation/runner"]
    subprocess.run(command, cwd=ROOT, check=True)
    exe = build / "native/debug/build/validation/runner" / ("runner.exe" if sys.platform == "win32" else "runner")
    ref = LibFLAC(library(None))
    outcomes = []
    for number in (10, 11):
        source = next((ROOT / "validation/cache/flac-test-files/uncommon").glob(f"{number} - *.flac"))
        expected, errors = ref.decode(source, framed=True, allow_lost_sync=True)
        assert errors == ([] if number == 10 else [0]), "unexpected libFLAC sync diagnostics"
        output = CACHE / f"uncommon-{number}.pcm"
        run = subprocess.run([str(exe), str(source), str(output), "raw"], capture_output=True, text=True,
                             encoding="utf-8", errors="replace", timeout=30)
        if run.returncode: raise RuntimeError(run.stdout + run.stderr)
        actual = output.read_bytes()
        if actual != expected: raise AssertionError(f"Raw corpus {number}: reference PCM mismatch")
        assert run.stdout == ("" if number == 10 else "skipped 0 895\n"), "unexpected resynchronization"
        outcomes.append(dict(source=str(source.relative_to(ROOT)), status="pass", reference_sync_errors=errors,
                             diagnostic=run.stdout, source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                             pcm_frame_bytes=len(expected), pcm_frame_sha256=hashlib.sha256(expected).hexdigest()))
    version = ctypes.c_char_p.in_dll(ref.dll, "FLAC__VERSION_STRING").value.decode()
    result = dict(generation_command="python scripts/review_raw.py --corpus", build_command=command,
                  oracle=f"libFLAC {version}", cases=outcomes, status="pass")
    (ROOT / "validation/evidence/review-raw-corpus.json").write_text(json.dumps(result, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(outcomes, indent=2))


if __name__ == "__main__":
    if "--corpus" in sys.argv: corpus()
    else: main()
