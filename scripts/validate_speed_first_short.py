"""Permanent reproduction of short-block review cases; no TEMP dependencies.

python scripts/validate_speed_first_short.py --baseline PATH --prepare
python scripts/validate_speed_first_short.py --baseline PATH --candidate PATH
Expected WB outputs are generated only by the accepted baseline CLI.
"""
import argparse
import hashlib
import json
import random
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / 'validation/cache/speed-first-short'
REPORT = ROOT / 'validation/evidence/speed-first-short.json'
BASELINE_SHA = 'e6817e77aafaa124a30d4e75b9a5f73beca10f0b0da967ddcc2e97c3397fe743'
FAILURES = {
    30: 'c6eab902c2ef08cec08e8a9971fe1f272d8dbe4788f7408e6e115adacbcb6513',
    45: '7d6491461a86e9345999e89b4a947a71298927899988135ac04be587f9a96172',
    54: '83355f6af1e5dae5c888cf6ea34452e23136631cbe2c1c7c418f0d5f3475e619',
    63: '6f75b016cf57963425015375891cfb87a689a9ee14c9f26801da66bf3a7deaa8',
    69: 'd9948c77e4faf930edfaf73aaf9cc0dd5172bb2e793c7e38509b2c97b509ccb5',
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def parameters():
    cases = []
    for bits in [4, 8, 12, 16, 20, 24, 25, 31, 32]:
        for channels in [1, 2, 4, 8]:
            for kind in ['sparse', 'piecewise']:
                i = len(cases)
                cases.append((bits, channels, kind, [37, 257, 1025][i % 3], [16, 192, 1024, 4096][i % 4], 8))
    cases += [(16, 2, 'piecewise', 32769, 32768, 8), (32, 8, 'sparse', 65536, 65535, 8), (24, 4, 'piecewise', 65535, 65535, 8)]
    for effort in range(8):
        cases += [(16, 2, 'piecewise', 4097, 1024, effort), (32, 8, 'sparse', 1025, 4096, effort)]
    for bits, channels in [(16, 1), (25, 4), (32, 8)]:
        for length in [16, 31, 36, 38, 63, 127, 255, 256, 257]:
            for kind in ['sparse', 'piecewise']:
                cases.append((bits, channels, kind, length, 4096, 8))
    return cases


def values_for(rng, bits, channels, kind, frames):
    lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    values = []
    for i in range(frames):
        for c in range(channels):
            if kind == 'sparse':
                value = rng.choice([lo, hi, lo + 1, hi - 1]) if (i + c * 13) % 97 == 0 else ((i + c) % 3) - 1
            else:
                phase = (i // 73) % 4
                value = ([lo, hi, 0, -1, 1][(i + c) % 5] if phase == 0 else
                         rng.randint(lo, hi) if phase == 1 else
                         ((i + c * 17) % 127 - 63) * (1 << max(0, bits - 9)) if phase == 2 else 0)
                value = max(lo, min(hi, value))
            values.append(value)
    return values


def encode(exe, raw, output, case):
    command = [str(exe), 'encode', str(raw), str(output), '--raw', '--sample-rate', '48000',
               '--channels', str(case['channels']), '--bits', str(case['bits']), '--effort', str(case['effort']),
               '--block-size', str(case['block_size'])]
    if case['variable']:
        command.append('--variable-block')
    result = subprocess.run(command, capture_output=True, timeout=180)
    assert result.returncode == 0, (command, result.stderr)
    return output.read_bytes()


def write_wb(fixtures):
    text = '// Generated by scripts/validate_speed_first_short.py --prepare.\n'
    text += '// Golden bytes come from independently accepted baseline CLI e6817e77..., never candidate.\n'
    for case, values, golden in fixtures:
        index = case['index']
        text += f'\n///|\ntest "encoder short blocks accepted baseline case {index}" {{\n'
        text += '  let samples : Array[Int] = [' + ', '.join(map(str, values)) + ']\n'
        text += f'  let config = EncoderConfig::new({{ sample_rate: 48000, channels: {case["channels"]}, bits_per_sample: {case["bits"]}, }}, block_size={case["block_size"]}, effort=8, variable_block={str(case["variable"]).lower()})\n'
        text += '  let actual = encode_pcm(samples, config)\n'
        if case['frames'] <= 256:
            text += '  let expected = b"' + ''.join(f'\\x{x:02x}' for x in golden) + '"\n'
            text += '  assert_eq(actual, expected)\n'
        else:
            text += f'  assert_true(actual.length() * 100 <= {len(golden)} * 103)\n'
        text += '  let audio = decode(actual)\n  assert_eq(audio.integrity, Md5Verified)\n  let mut cursor = 0\n'
        text += '  for frame in audio.frames {\n    for i = 0; i < frame.block_size; i = i + 1 {\n      for channel in frame.channels {\n        assert_eq(channel[i], samples[cursor])\n        cursor += 1\n      }\n    }\n  }\n  assert_eq(cursor, samples.length())\n}\n'
    (ROOT / 'encoder_short_blocks_wbtest.mbt').write_text(text, encoding='utf-8')


def main():
    global WORK
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--baseline', required=True, type=Path)
    parser.add_argument('--candidate', type=Path)
    parser.add_argument('--prepare', action='store_true')
    parser.add_argument('--report', type=Path, default=REPORT)
    parser.add_argument('--work', type=Path, default=WORK)
    args = parser.parse_args()
    WORK = args.work.resolve()
    if not args.prepare and args.report.exists():
        raise FileExistsError('Preserve existing short-block evidence; select a new --report')
    assert sha(args.baseline.read_bytes()) == BASELINE_SHA
    assert args.prepare or args.candidate
    WORK.mkdir(parents=True, exist_ok=True)
    from validate import LibFLAC, library
    oracle = LibFLAC(library(None))
    flac = ROOT / 'validation/cache/libflac/flac-1.5.0-win/Win64/flac.exe'
    rng = random.Random(202609291253)
    rows, fixtures = [], []
    candidate_sha = sha(args.candidate.read_bytes()) if args.candidate else None
    for index, (bits, channels, kind, frames, block, effort) in enumerate(parameters()):
        values = values_for(rng, bits, channels, kind, frames)
        raw = b''.join(v.to_bytes((bits + 7) // 8, 'little', signed=True) for v in values)
        if index in FAILURES:
            assert sha(raw) == FAILURES[index], ('review fixture differs', index)
        case = dict(index=index, bits=bits, channels=channels, pattern=kind, frames=frames,
                    block_size=block, effort=effort, variable=index % 3 == 1, pcm_sha256=sha(raw))
        source = WORK / f'{index:03}.raw'
        source.write_bytes(raw)
        baseline_path = WORK / f'{index:03}-baseline.flac'
        baseline = encode(args.baseline, source, baseline_path, case)
        case.update(baseline_sha256=sha(baseline), baseline_bytes=len(baseline))
        props, decoded = oracle.decode(baseline_path)
        assert props == (channels, bits, 48000) and decoded == values
        checked = subprocess.run([str(flac), '--silent', '-t', str(baseline_path)], capture_output=True, timeout=120)
        assert checked.returncode == 0
        if index in FAILURES or (index >= 91 and bits == 16 and frames in [16, 255, 256, 257] and kind == 'piecewise'):
            fixtures.append((case.copy(), values, baseline))
        if not args.prepare:
            output = WORK / f'{index:03}-candidate.flac'
            candidate = encode(args.candidate, source, output, case)
            props, decoded = oracle.decode(output)
            assert props == (channels, bits, 48000) and decoded == values, ('PCM', index)
            checked = subprocess.run([str(flac), '--silent', '-t', str(output)], capture_output=True, timeout=120)
            assert checked.returncode == 0, ('CRC/MD5', index, checked.stderr)
            exact_required = effort < 8 or min(block, frames) <= 256
            case.update(candidate_sha256=sha(candidate), candidate_bytes=len(candidate),
                        size_ratio=len(candidate) / len(baseline), exact_required=exact_required,
                        bytes_equal=candidate == baseline, pcm='independent libFLAC exact', crc_md5='libFLAC -t pass')
            assert not exact_required or candidate == baseline, ('short/low effort bitstream differs', index)
        rows.append(case)
    if args.prepare:
        write_wb(fixtures)
        output = WORK / 'prepared.json'
    else:
        assert sha(args.candidate.read_bytes()) == candidate_sha
        output = args.report
    groups = {'confirmed_five': [r for r in rows if r['index'] in FAILURES],
              'original_75_effort8': rows[:75], 'neighbors_54': rows[91:]}
    summary = {}
    if not args.prepare:
        for name, group in groups.items():
            ratio = sum(r['candidate_bytes'] for r in group) / sum(r['baseline_bytes'] for r in group)
            failures = [r['index'] for r in group if r['size_ratio'] > 1.03]
            summary[name] = dict(cases=len(group), aggregate_ratio=ratio, above_three_percent=failures)
    proof = dict(status='prepared' if args.prepare else 'pass' if all(g['aggregate_ratio'] <= 1.01 and not g['above_three_percent'] for g in summary.values()) else 'quality-fail',
                 seed=202609291253, baseline_sha256=BASELINE_SHA, candidate_sha256=candidate_sha,
                 script_sha256=sha(Path(__file__).read_bytes()), cases=rows, quality_groups=summary,
                 original_review_cases=91, neighboring_cases=54,
                 scope='Full byte identity required for all actual blocks <=256 and efforts0-7; independent PCM and libFLAC CRC/MD5 for all cases. No timing claims.')
    output.write_text(json.dumps(proof, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'status': proof['status'], 'cases': len(rows), 'groups': summary}))
    if proof['status'] == 'quality-fail':
        raise SystemExit(1)


if __name__ == '__main__':
    main()
