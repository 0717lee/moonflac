"""Generate the disposable prototype's RFC1321 rounds; never edit production.

The archived preimage contains the existing reviewed RFC1321 K/S tables.
All 64 constants are additionally checked against the RFC sine definition.
"""
import hashlib
import json
import math
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / '_build/faster-than-libflac/prototype5-source/md5.mbt'
ARCHIVE = ROOT / 'validation/baselines/faster-than-libflac-md5-preunroll.mbt.txt'
if not ARCHIVE.exists():
    ARCHIVE.write_bytes(TARGET.read_bytes())
old = ARCHIVE.read_text(encoding='utf-8')
constants = re.findall(r'0x[0-9a-f]+U', old.split('let md5_constants')[1].split('= [')[1].split(']')[0])
assert len(constants) == 64
assert [int(k[2:-1],16) for k in constants] == [int(abs(math.sin(i+1))*2**32) for i in range(64)]
shifts = [7,12,17,22,5,9,14,20,4,11,16,23,6,10,15,21]
lines = ['///|', '// Generated by scripts/faster-than-libflac-md5-unroll.py from the archived RFC1321 tables.',
         '// Private block contract: callers invoke only with exactly 64 pending bytes;',
         '// new/digest allocate exactly 16 scratch words and four state words.',
         'fn Md5::block(self : Md5, bytes : Array[Byte]) -> Unit {',
         '  let words = self.words', '  for i in 0..<16 {', '    let j = i * 4',
         '    words.unsafe_set(i, bytes.unsafe_get(j).to_uint() |',
         '      (bytes.unsafe_get(j+1).to_uint() << 8) |',
         '      (bytes.unsafe_get(j+2).to_uint() << 16) |',
         '      (bytes.unsafe_get(j+3).to_uint() << 24))', '  }']
for n,letter in enumerate('abcd'):
    lines.append(f'  let mut {letter} = self.h.unsafe_get({n})')
for i in range(64):
    a,b,c,d = ('abcd','dabc','cdab','bcda')[i%4]
    group=i//16
    f=[f'(({b} & {c}) | ({b}.lnot() & {d}))',
       f'(({d} & {b}) | ({d}.lnot() & {c}))',f'({b} ^ {c} ^ {d})',f'({c} ^ ({b} | {d}.lnot()))'][group]
    g=[i,(5*i+1)%16,(3*i+5)%16,(7*i)%16][group]
    shift=shifts[group*4+i%4]
    lines.extend([f'  // RFC1321 operation {i+1}: round {group+1}, word {g}, rotate {shift}.',
                  f'  let t{i} = {a} + {f} + {constants[i]} + words.unsafe_get({g})',
                  f'  {a} = {b} + ((t{i} << {shift}) | (t{i} >> {32-shift}))'])
for n,letter in enumerate('abcd'):
    lines.append(f'  self.h.unsafe_set({n}, self.h.unsafe_get({n}) + {letter})')
lines.append('}')
prefix=old[old.index('///|\n/// Incremental'):old.index('///|\nfn Md5::block')]
suffix=old[old.index('///|\nfn Md5::update'):]
new=prefix+'\n'.join(lines)+'\n\n'+suffix
TARGET.write_text(new,encoding='utf-8')
# Recompute all 232 independent depth/channel expected digests without writing
# the production fixture; existing MoonBit fixture logic is retained verbatim.
fixture=runpy.run_path(str(ROOT/'scripts/generate_md5_pcm_fixture.py'))
expected=[fixture['expected'](bits,channels) for bits in range(4,33) for channels in range(1,9)]
fixture_text=(TARGET.parent/'md5_pcm_wbtest.mbt').read_text(encoding='utf-8')
encoded=re.findall(r'b"((?:\\x[0-9a-f]{2}){16})"',fixture_text)[:232]
assert [bytes.fromhex(s.replace('\\x','')) for s in encoded] == expected
report={'prototype':str(TARGET.relative_to(ROOT)), 'archive':str(ARCHIVE.relative_to(ROOT)),
        'old_sha256':hashlib.sha256(ARCHIVE.read_bytes()).hexdigest(),
        'new_sha256':hashlib.sha256(TARGET.read_bytes()).hexdigest(),
        'rfc_constants_checked':64,'hashlib_pcm_cases_recomputed':232,
        'production_changed':False,'performance_measured':False}
(ROOT/'validation/evidence/faster-than-libflac-md5-unroll-generation.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report))
