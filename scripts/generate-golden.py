#!/usr/bin/env python3
"""Generate committed cross-backend golden tests from independent libFLAC PCM."""
from pathlib import Path
import hashlib
import json
import struct
from validate import CACHE, ROOT, LibFLAC, library, packed

ref=LibFLAC(library(None))
dest=ROOT/"validation/golden"
dest.mkdir(parents=True,exist_ok=True)
(dest/"moon.pkg").write_text('import { "0717lee/moonflac" @flac }\n',encoding="utf-8")
sources=[CACHE/"generated"/f"depth-{b:02}-channels-{c}.flac" for b,c in [(4,1),(8,2),(12,3),(16,4),(20,5),(24,6),(28,7),(32,8)]]
sources += [CACHE/"generated/ogg-16-2.oga"]
sources += [next((CACHE/"flac-test-files/subset").glob(f"{n:02} - *.flac")) for n in (12,16,31,61,64)]
manifest=[]
def literal(data): return 'b"'+''.join(f'\\x{x:02x}' for x in data)+'"'
for index,source in enumerate(sources):
    data=source.read_bytes()
    source_sha256=hashlib.sha256(data).hexdigest()
    if source.parent.name=="subset":
        framed,_=ref.decode(source,framed=True)
        count,rate,bits,channels=struct.unpack_from("<IIII",framed)
        pcm=struct.unpack_from("<"+"i"*(count*channels),framed,16)
        pos=4
        while True:
            last=data[pos]&128
            length=int.from_bytes(data[pos+1:pos+4],"big")
            pos+=4+length
            if last: break
        info=bytearray(data[8:42])
        # Repackage the independently encoded first frame as a complete file.
        # Only metadata total, frame size bounds and digest are changed.
        info[4:10]=bytes(6)
        info[10:18]=((int.from_bytes(info[10:18],"big")>>36<<36)|count).to_bytes(8,"big")
        expected=packed(pcm,bits)
        info[18:34]=hashlib.md5(expected).digest()
        data=b"fLaC\x80\x00\x00\x22"+info+data[pos:ref.frame_positions[0]]
    else:
        (_,bits,_),pcm=ref.decode(source)
        expected=packed(pcm,bits)
    name=f"golden_{index:02}_test.mbt"
    code=f'''// Generated by scripts/generate-golden.py. Expected samples: libFLAC 1.5.0.
// Source: {source.name}
///|
test "independent PCM {source.stem}" {{
  let audio = @flac.decode({literal(data)})
  let expected = {literal(expected)}
  let mut offset = 0
  for frame in audio.frames {{
    let actual = @flac.frame_pcm(frame)
    assert_eq(actual, expected[offset:offset + actual.length()].to_owned())
    offset += actual.length()
  }}
  assert_eq(offset, expected.length())
}}
'''
    (dest/name).write_text(code,encoding="utf-8")
    manifest.append(dict(test=name,source=str(source.relative_to(ROOT)),source_sha256=source_sha256,flac_sha256=hashlib.sha256(data).hexdigest(),pcm_sha256=hashlib.sha256(expected).hexdigest(),pcm_bytes=len(expected)))
(dest/"sources.json").write_text(json.dumps(manifest,indent=2)+"\n")
print(f"Wrote {len(sources)} golden tests, {sum(x.stat().st_size for x in dest.glob('*.mbt'))} source bytes")
